// Writes src/page/font-data.ts: the outlines of the page font, flattened to integer polygons in
// font units, so the renderer draws text with no font engine on the tablet (#379).
//
// The font is Figtree (SIL Open Font License 1.1, design/fonts/), the Ink Tools brand face, at the
// two weights a page uses: 400 for clues and the footer, 700 for givens. Curves are cut into
// straight segments here, once, on the Mac; the renderer only fills polygons.
//
// Run from the repository root:
//   swift packages/puzzle-core/scripts/font-outlines.swift > packages/puzzle-core/src/page/font-data.ts
import CoreText
import Foundation

let fontPath = "design/fonts/Figtree[wght].ttf"
let weights: [Int] = [400, 700]
/// Printable ASCII, the footer's separators, and the letters and quotes of Portuguese, Spanish,
/// German and French text: Latin-1's À to ÿ (without the division sign), œ, Œ, « and » (#455).
let accented: [Character] = (0xC0...0xFF).filter { $0 != 0xF7 && $0 != 0xD7 }.map { Character(UnicodeScalar($0)!) } + ["œ", "Œ", "«", "»"]
let characters: [Character] = (32...126).map { Character(UnicodeScalar($0)!) } + ["·", "×", "–"] + accented
/// Segments per curve: enough that a 180 px given shows no corner.
let quadSegments = 6
let cubicSegments = 8
/// A contour needs three points, six numbers, to enclose anything.
let minContourNumbers = 6
/// The variation axis tag of the weight, `wght`.
let weightAxis = 0x7767_6874

guard let provider = CGDataProvider(filename: fontPath), let base = CGFont(provider) else {
  FileHandle.standardError.write("cannot read \(fontPath)\n".data(using: .utf8)!)
  exit(1)
}
let unitsPerEm = Int(base.unitsPerEm)

func font(weight: Int) -> CTFont {
  let attributes = [kCTFontVariationAttribute: [weightAxis: weight]] as CFDictionary
  let descriptor = CTFontDescriptorCreateWithAttributes(attributes)
  return CTFontCreateWithGraphicsFont(base, CGFloat(unitsPerEm), nil, descriptor)
}

func round(_ p: CGPoint) -> [Int] { [Int(p.x.rounded()), Int(p.y.rounded())] }

/// The glyph's contours as flat lists x0, y0, x1, y1, ..., y up from the baseline.
func contours(_ path: CGPath) -> [[Int]] {
  var result: [[Int]] = []
  var current: [Int] = []
  var last = CGPoint.zero
  func add(_ p: CGPoint) {
    let point = round(p)
    if current.count >= 2, current[current.count - 2] == point[0], current[current.count - 1] == point[1] { return }
    current += point
  }
  func close() {
    if current.count >= minContourNumbers { result.append(current) }
    current = []
  }
  path.applyWithBlock { element in
    let e = element.pointee
    switch e.type {
    case .moveToPoint:
      close()
      last = e.points[0]
      add(last)
    case .addLineToPoint:
      last = e.points[0]
      add(last)
    case .addQuadCurveToPoint:
      let c = e.points[0], end = e.points[1]
      for i in 1...quadSegments {
        let t = CGFloat(i) / CGFloat(quadSegments), u = 1 - t
        add(CGPoint(x: u * u * last.x + 2 * u * t * c.x + t * t * end.x,
                    y: u * u * last.y + 2 * u * t * c.y + t * t * end.y))
      }
      last = end
    case .addCurveToPoint:
      let c1 = e.points[0], c2 = e.points[1], end = e.points[2]
      for i in 1...cubicSegments {
        let t = CGFloat(i) / CGFloat(cubicSegments), u = 1 - t
        let a = u * u * u, b = 3 * u * u * t, c = 3 * u * t * t, d = t * t * t
        add(CGPoint(x: a * last.x + b * c1.x + c * c2.x + d * end.x,
                    y: a * last.y + b * c1.y + c * c2.y + d * end.y))
      }
      last = end
    case .closeSubpath:
      close()
    @unknown default:
      break
    }
  }
  close()
  return result
}

var out = """
// Generated by packages/puzzle-core/scripts/font-outlines.swift from design/fonts/Figtree[wght].ttf
// (SIL Open Font License 1.1, see ../../NOTICE.md); do not edit by hand (#379).
// Each glyph: its advance, then each contour as x0, y0, x1, y1, ... in font units, y up.
/* eslint-disable */

"""
let regular = font(weight: weights[0])
out += "export const FONT_METRICS = { unitsPerEm: \(unitsPerEm), ascent: \(Int(CTFontGetAscent(regular).rounded())), "
out += "descent: \(Int(CTFontGetDescent(regular).rounded())), capHeight: \(Int(CTFontGetCapHeight(regular).rounded())) } as const;\n\n"
out += "export const FONT_GLYPHS: Readonly<Record<number, Readonly<Record<string, readonly (number | readonly number[])[]>>>> = {\n"
for weight in weights {
  let ct = font(weight: weight)
  out += "  \(weight): {\n"
  for ch in characters {
    let units = Array(String(ch).utf16)
    var glyphs = [CGGlyph](repeating: 0, count: units.count)
    guard CTFontGetGlyphsForCharacters(ct, units, &glyphs, units.count), glyphs[0] != 0 else {
      FileHandle.standardError.write("no glyph for \(ch)\n".data(using: .utf8)!)
      exit(1)
    }
    var advance = CGSize.zero
    CTFontGetAdvancesForGlyphs(ct, .horizontal, &glyphs, &advance, 1)
    var parts = ["\(Int(advance.width.rounded()))"]
    if let path = CTFontCreatePathForGlyph(ct, glyphs[0], nil) {
      parts += contours(path).map { "[" + $0.map(String.init).joined(separator: ",") + "]" }
    }
    let key = ch == "\\" || ch == "'" ? "\\\(ch)" : String(ch)
    out += "    '\(key)': [\(parts.joined(separator: ","))],\n"
  }
  out += "  },\n"
}
out += "};\n"
print(out, terminator: "")
